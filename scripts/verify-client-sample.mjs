// Read-only checks of the approved temporary dataset in an isolated browser.
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {chromium,expect} from '@playwright/test';
const directory='.cloud-build/client-sample',origin='https://fodo.am-agent2026.workers.dev';
const owner=JSON.parse(await readFile('.cloud-build/initial-owner.json','utf8'));
const run=JSON.parse(await readFile(directory+'/run.json','utf8'));
await mkdir(directory+'/screenshots',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const result={origin,checks:[],errors:[]};
let page;
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});page=await context.newPage();
 page.on('pageerror',error=>result.errors.push(error.message));
 await page.goto(origin,{waitUntil:'networkidle'});
 await page.getByLabel('البريد الإلكتروني',{exact:true}).fill(owner.email);
 await page.getByLabel('كلمة المرور',{exact:true}).fill(owner.password);
 await page.getByRole('button',{name:'تسجيل الدخول',exact:true}).click();
 await expect(page.getByRole('heading',{name:'نظرة عامة',exact:true})).toBeVisible({timeout:30000});
 await expect(page.getByText('التطبيق جاهز للفتح دون اتصال',{exact:false})).toBeVisible({timeout:30000});
 const response=await context.request.get(origin+'/api/v1/bootstrap');
 if(!response.ok())throw Error('Hosted snapshot unavailable');
 const snapshot=await response.json();
 if(snapshot.organizationId!==run.organizationId||snapshot.generation!==run.generation)throw Error('Unexpected trial workspace');
 if(snapshot.items.length!==338||snapshot.menuItems.length!==99||snapshot.recipes.length!==100)throw Error('Dataset counts differ');
 if(snapshot.reconciliation.some(r=>!r.matches)||snapshot.balances.some(b=>Number(b.quantity)<0))throw Error('Stock reconciliation differs');
 result.checks.push('Client sign-in, complete trial snapshot and stock reconciliation');
 const profile=page.getByRole('dialog',{name:'بيانات المؤسسة',exact:true});
 await expect(profile).toHaveCount(0);
 await page.getByRole('button',{name:'المؤسسة الحالية',exact:true}).click();
 await expect(profile.getByRole('heading',{name:'واحة أولاد سعد',exact:true})).toBeVisible();
 await expect.poll(()=>profile.getByRole('img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0))).toBe(true);
 await page.keyboard.press('Escape');
 const open=async name=>{await page.getByRole('button',{name,exact:true}).click();await expect(page.getByRole('heading',{name,exact:true,level:1})).toBeVisible();};
 await open('المخزون');
 await expect(page.getByText('صلصة طماطم مطبوخة',{exact:true}).first()).toBeVisible();
 await page.getByRole('button',{name:'تعديل رصيد صلصة طماطم مطبوخة',exact:true}).click();
 const balance=page.getByRole('dialog',{name:'تعديل الرصيد',exact:true});
 await expect(balance.getByLabel('الرصيد الجديد',{exact:true})).toHaveValue('15.6');
 await page.keyboard.press('Escape');
 await expect(balance).toHaveCount(0);
 result.checks.push('Produced stock and editable balance; cancelled without saving');
 await open('الوصفات والتكاليف');
 await expect(page.locator('.recipe-list-row')).toHaveCount(100);
 await page.getByLabel('بحث الوصفات',{exact:true}).fill('نصف فرخة مندي');
 await page.locator('.recipe-list-row').getByRole('button').click();
 await page.getByLabel('مصدر تقدير التكلفة',{exact:true}).selectOption('latest_receipt');
 await expect(page.getByTestId('recipe-unit-cost')).not.toHaveText('— ج.م');
 await expect(page.locator('.recipe-detail')).not.toContainText('التكلفة غير مكتملة');
 await page.getByRole('button',{name:'إنشاء مسودة إصدار جديد',exact:true}).click();
 await expect(page.getByRole('checkbox',{name:'خصم عند البيع فرخة',exact:true})).toBeChecked();
 await expect(page.getByRole('checkbox',{name:'خصم عند البيع زيت رامبو',exact:true})).not.toBeChecked();
 await page.getByRole('button',{name:'إغلاق الوصفة',exact:true}).click();
 await page.screenshot({path:directory+'/screenshots/recipes.png',fullPage:true,animations:'disabled'});
 result.checks.push('100 recipes, complete estimated cost and selective ingredient deduction; editor cancelled');
 await open('المبيعات');
 await expect(page.locator('tbody tr')).toHaveCount(99);
 await page.getByRole('tab',{name:'سجل المبيعات',exact:true}).click();
 await expect(page.getByText('مبيعات مجموعة كبيرة - مراجعة النقص',{exact:false}).first()).toBeVisible();
 await expect(page.locator('.sales-shortage-notice')).toContainText('المبيعات مقبولة');
 await expect(page.locator('.stock-shortage-warning tbody tr').first()).toBeVisible();
 await page.locator('.stock-shortage-warning').screenshot({path:directory+'/screenshots/sales-shortage.png',animations:'disabled'});
 await page.getByRole('tab',{name:'الاستهلاك النظري',exact:true}).click();
 await page.getByLabel('أساس تقدير التكلفة',{exact:false}).selectOption('latest_receipt');
 await expect(page.getByRole('heading',{name:'الاستهلاك النظري وتكلفة المبيعات',exact:true})).toBeVisible();
 await expect(page.locator('tbody tr').first()).toBeVisible();
 await expect(page.locator('.operation-summary')).not.toContainText('غير مكتملة');
 await page.screenshot({path:directory+'/screenshots/sales-report.png',fullPage:true,animations:'disabled'});
 result.checks.push('99 sales mappings, accepted shortage history and complete theoretical consumption report');
 await open('المشتريات');
 await expect(page.getByText('توريد المواد الغذائية الأسبوعي',{exact:false}).first()).toBeVisible();
 await expect(page.getByText('طلب لحوم للأسبوع القادم',{exact:false}).first()).toBeVisible();
 await expect(page.getByText('استلام أول للتوريد الأسبوعي',{exact:false}).first()).toBeVisible();
 await expect(page.getByText('استكمال التوريد الأسبوعي',{exact:false}).first()).toBeVisible();
 await open('مرتجعات الموردين');
 await expect(page.getByText('إرجاع زيت بسبب تلف العبوة',{exact:false}).first()).toBeVisible();
 await open('الإنتاج والتحضير');
 await expect(page.getByText('تحضير صلصة الطماطم - دفعة 1',{exact:false}).first()).toBeVisible();
 await expect(page.getByText('تحضير صلصة الطماطم - دفعة 2',{exact:false}).first()).toBeVisible();
 await expect(page.getByTestId('production-output-cost')).toHaveCount(2);
 result.checks.push('Purchases, partial/final receiving, source-linked return and two production batches');
 await page.setViewportSize({width:390,height:844});
 await open('المبيعات');
 await page.getByRole('tab',{name:'الاستهلاك النظري',exact:true}).click();
 await page.getByLabel('أساس تقدير التكلفة',{exact:false}).selectOption('latest_receipt');
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:directory+'/screenshots/mobile-report.png',animations:'disabled'});
 await context.setOffline(true);
 await page.reload({waitUntil:'domcontentloaded'});
 await open('الوصفات والتكاليف');
 await expect(page.locator('.recipe-list-row')).toHaveCount(100);
 await open('المبيعات');
 await expect(page.locator('tbody tr')).toHaveCount(99);
 await page.getByRole('tab',{name:'سجل المبيعات',exact:true}).click();
 await expect(page.locator('.sales-shortage-notice')).toContainText('المبيعات مقبولة');
 result.checks.push('Mobile report without overflow; offline reload retains recipes, mappings and shortage records');
 await context.setOffline(false);
 await open('مركز المزامنة');
 await page.getByRole('button',{name:'تسجيل الخروج',exact:true}).click();
 await expect(page.getByRole('button',{name:'تسجيل الدخول',exact:true})).toBeVisible();
 if(result.errors.length)throw Error(result.errors.join('; '));
}catch(error){
 result.failure=error.message;
 if(page)await page.screenshot({path:directory+'/screenshots/failure.png',animations:'disabled'}).catch(()=>{});
 throw error;
}finally{
 await browser.close();
 await writeFile(directory+'/browser-verification.json',JSON.stringify(result,null,2));
}
console.log(JSON.stringify(result,null,2));
