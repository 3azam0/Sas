import {test,expect} from '@playwright/test';

test('item composition opens an offline stocked recipe and reuses its definition without changing stock',async({page,context})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'فتح مجموعة المشاوي',exact:true}).click();
 await expect(page.getByText('التطبيق جاهز للفتح دون اتصال',{exact:false})).toBeVisible({timeout:30000});
 const before=await(await page.request.get('/api/v1/bootstrap')).json();
 const suffix=Date.now().toString(),name=`خلطة كفتة ${suffix}`,sku=`CMP-${suffix}`;
 await page.getByLabel('الموقع',{exact:true}).selectOption('central');
 await page.getByRole('button',{name:'إعداد المخزون',exact:true}).click();
 await context.setOffline(true);
 await page.getByRole('button',{name:'إضافة مادة',exact:true}).click();
 await page.getByLabel('اسم السجل',{exact:true}).fill(name);
 await page.getByLabel('كود المادة',{exact:true}).fill(sku);
 await page.getByLabel('وحدة المخزون',{exact:true}).selectOption('كجم');
 await page.getByLabel('فتح إعداد المكونات بعد الحفظ',{exact:true}).check();
 await page.getByRole('button',{name:'حفظ الإعدادات',exact:true}).click();
 await expect(page.getByRole('heading',{name:`مكونات الصنف: ${name}`,exact:true})).toBeVisible();
 await expect(page.getByLabel('اسم الوصفة',{exact:true})).toHaveValue(name);
 await expect(page.getByLabel('كود الوصفة',{exact:true})).toHaveValue(`BOM-${sku}`);
 await expect(page.getByLabel('نوع ناتج الوصفة',{exact:true})).toHaveValue('stocked');
 await expect(page.getByLabel('وحدة ناتج الوصفة',{exact:true})).toHaveValue('كجم');
 await expect(page.getByLabel('وحدة ناتج الوصفة',{exact:true})).toBeDisabled();
 const outputId=await page.getByLabel('مادة ناتج الوصفة',{exact:true}).inputValue();
 await page.getByLabel('ناتج دفعة الوصفة',{exact:true}).fill('2');
 await page.getByRole('button',{name:'إضافة مكون',exact:true}).click();
 await expect(page.getByLabel('مكون الوصفة 1',{exact:true}).locator(`option[value="${outputId}"]`)).toHaveCount(0);
 await page.getByLabel('مكون الوصفة 1',{exact:true}).selectOption('beef');
 await page.getByLabel('كمية مكون الوصفة 1',{exact:true}).fill('1');
 await page.getByRole('button',{name:'حفظ مسودة الوصفة',exact:true}).click();
 await page.getByRole('button',{name:'نشر إصدار',exact:true}).click();
 await page.reload();
 await page.getByRole('button',{name:'الوصفات والتكاليف',exact:true}).click();
 await expect(page.getByRole('button',{name:new RegExp(name)})).toBeVisible();
 await page.getByRole('button',{name:new RegExp(name)}).click();
 await expect(page.getByText('محفوظ محلياً',{exact:true}).first()).toBeVisible();
 const beef=before.balances.find((b:any)=>b.itemId==='beef'&&b.locationId==='central');
 const expected=new Intl.NumberFormat('ar-EG',{maximumFractionDigits:2}).format(Number(beef.value)/Number(beef.quantity)/2);
 await expect(page.getByTestId('recipe-unit-cost')).toHaveText(expected+' ج.م');
 await context.setOffline(false);
 await page.getByRole('button',{name:'مزامنة الآن',exact:true}).first().click();
 await expect.poll(async()=>{const s=await(await page.request.get('/api/v1/bootstrap')).json();return s.recipes.find((r:any)=>r.definition.outputItemId===outputId)?.state;},{timeout:30000}).toBe('published');
 const accepted=await(await page.request.get('/api/v1/bootstrap')).json();
 expect(accepted.items.find((i:any)=>i.id===outputId)?.unitId).toBe('كجم');
 expect(accepted.balances).toEqual(before.balances);
 expect(accepted.entries).toEqual(before.entries);
 await page.getByRole('button',{name:'إعداد المخزون',exact:true}).click();
 await page.getByLabel('بحث الإعدادات',{exact:true}).fill(name);
 const row=page.getByRole('row').filter({hasText:name});
 await expect(row.getByText('صنف مركّب · له وصفة مكونات',{exact:true})).toBeVisible();
 await context.setOffline(true);
 await row.getByRole('button',{name:'مكونات الصنف',exact:true}).click();
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'إنشاء مسودة إصدار جديد',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:`مكونات الصنف: ${name}`,exact:true})).toHaveCount(0);
 await context.setOffline(false);
 const after=await(await page.request.get('/api/v1/bootstrap')).json();
 expect(after.recipes.filter((r:any)=>r.definition.outputItemId===outputId)).toHaveLength(1);
 expect(after.recipeVersions.filter((v:any)=>v.definition.outputItemId===outputId)).toHaveLength(1);
 expect(after.balances).toEqual(before.balances);
 expect(after.entries).toEqual(before.entries);
 await page.screenshot({path:'../Fodo-Item-Composition.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'../Fodo-Item-Composition-Mobile.png',fullPage:true});
});
